SMALL_W, SMALL_H = 4, 6


def small_width(s):
    return len(s) * SMALL_W


def draw_small(px, x, y, s, color):
    for ch in s:
        glyph = SMALL.get(ch, SMALL[' '])
        for row in range(SMALL_H):
            bits = glyph[row]
            for col in range(SMALL_W):
                if bits & (0x8 >> col):
                    px_x, px_y = x + col, y + row
                    if 0 <= px_x < W and 0 <= px_y < H:
                        px[px_y * W + px_x] = color
        x += SMALL_W


def text_width(s, scale):
    return len(s) * 8 * scale


def draw_text(px, x, y, s, color, scale=1):
    for ch in s:
        glyph = FONT.get(ch, FONT[' '])
        for row in range(8):
            bits = glyph[row]
            for col in range(8):
                if bits & (0x80 >> col):
                    for dy in range(scale):
                        for dx in range(scale):
                            px_x = x + col * scale + dx
                            px_y = y + row * scale + dy
                            if 0 <= px_x < W and 0 <= px_y < H:
                                px[px_y * W + px_x] = color
        x += 8 * scale


def build():
    px = bytearray([0]) * (W * H)

    # background band behind the title, a touch darker than the field
    for y in range(0, H):
        for x in range(W):
            px[y * W + x] = 0

    for y in range(56, 120):
        for x in range(W):
            px[y * W + x] = 1

    # thin accent rules
    for x in range(W):
        px[54 * W + x] = 4
        px[121 * W + x] = 4

    # title, centred, scaled up
    title = "LA64M68"
    s = 3
    draw_text(px, (W - text_width(title, s)) // 2, 72, title, 2, s)

    # a single line below the title -- the licence notice and nothing else
    def centred(y, s, color, scale=1):
        w = text_width(s, scale)
        # refuse to clip: a line wider than the canvas would silently vanish
        assert w <= W, "line %r is %d px wide, canvas is %d" % (s, w, W)
        draw_text(px, (W - w) // 2, y, s, color, scale)

    line = "Non-Profit GNU/GPLv3+"
    assert small_width(line) <= W, "secondary line too wide"
    draw_small(px, (W - small_width(line)) // 2, 152, line, 3)
    return px


def to_planar(px):
    """Amiga Denise: 4 bitplanes, each row of all planes stored together."""
    planes = 4
    row_bytes = W // 8
    out = bytearray()
    for y in range(H):
        for p in range(planees := planes):
            row = bytearray(row_bytes)
            for x in range(W):
                if (px[y * W + x] >> p) & 1:
                    row[x >> 3] |= 0x80 >> (x & 7)
            out += row
    return bytes(out)


def to_st(px):
    """Atari ST low res: 4 planes interleaved as 16-bit words per row."""
    out = bytearray()
    for y in range(H):
        for p in range(4):
            row = bytearray(W // 8)
            for x in range(W):
                if (px[y * W + x] >> p) & 1:
                    row[x >> 3] |= 0x80 >> (x & 7)
            out += row
    return bytes(out)


def emit_assets(px):
    """Write the splash as binary assets next to the executable.

    Keeping the raster out of the C source matters: the image is 64 KB of
    chunky pixels plus 2x32 KB of planar data, which would be ~650 KB of
    generated source. As files in the program root they stay small, and it
    matches how LA64M68 keeps everything self-contained in its own directory.
    """
    import os
    os.makedirs("assets", exist_ok=True)
    with open("assets/splash.pal", "wb") as f:
        for c in PALETTE:
            f.write(bytes([(c >> 8) & 0xFF, c & 0xFF]))
    with open("assets/splash.chunky", "wb") as f:
        f.write(bytes(px))
    with open("assets/splash.planar", "wb") as f:
        f.write(to_planar(px))
    with open("assets/splash.st", "wb") as f:
        f.write(to_st(px))

